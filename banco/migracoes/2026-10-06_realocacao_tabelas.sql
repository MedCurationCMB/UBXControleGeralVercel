CREATE POLICY rls_projeto ON public.realocacoes FOR ALL TO anon, authenticated
  USING (projeto_id = (SELECT public.app_projeto_rls()))
  WITH CHECK (projeto_id = (SELECT public.app_projeto_rls()));
ALTER TABLE public.realocacao_itens ENABLE ROW LEVEL SECURITY;
CREATE POLICY rls_projeto ON public.realocacao_itens FOR ALL TO anon, authenticated
  USING (projeto_id = (SELECT public.app_projeto_rls()))
  WITH CHECK (projeto_id = (SELECT public.app_projeto_rls()));
