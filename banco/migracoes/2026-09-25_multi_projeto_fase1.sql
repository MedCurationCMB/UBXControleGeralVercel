-- 2. Projeto ativo (vem do cabecalho HTTP x-projeto-id) -------------------------------------
-- nullif(...,''): depois de uma transacao o Postgres deixa o parametro como texto vazio, nao NULL.
CREATE FUNCTION public.app_projeto_ativo() RETURNS integer LANGUAGE sql STABLE AS $$
  SELECT nullif(nullif(current_setting('request.headers', true), '')::json ->> 'x-projeto-id', '')::integer
$$;
-- Valor padrao do projeto_id. O "1" e temporario (fase 4 remove): sem cabecalho, cai no UBX.
CREATE FUNCTION public.app_projeto_default() RETURNS integer LANGUAGE sql STABLE AS $$
  SELECT coalesce(public.app_projeto_ativo(), 1)
$$;

