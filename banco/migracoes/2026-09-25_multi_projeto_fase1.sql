-- Trava de soma das parcelas: le a configuracao de fluxo do projeto do pedido.
CREATE OR REPLACE FUNCTION public.validar_limite_parcelas_pedido() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  v_pedido  numeric;
  v_projeto integer;
  v_soma    numeric;
BEGIN
  IF NEW.pedido_id IS NULL OR NEW.valor_pagar IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT valor_pedido, projeto_id INTO v_pedido, v_projeto FROM pedidos_solicitados WHERE id = NEW.pedido_id;
  IF v_pedido IS NULL THEN
    RETURN NEW;
  END IF;

  IF (SELECT valor FROM config WHERE chave = 'fluxo_sistema' AND projeto_id = v_projeto LIMIT 1) = '3' THEN
    RETURN NEW;
  END IF;

  SELECT COALESCE(SUM(valor_pagar), 0) INTO v_soma
    FROM controle_pagamentos
   WHERE pedido_id = NEW.pedido_id
     AND id IS DISTINCT FROM NEW.id;

  IF v_soma + NEW.valor_pagar > v_pedido THEN
    RAISE EXCEPTION 'Soma das parcelas (R$ %) excede o valor autorizado do pedido (R$ %).',
      to_char(v_soma + NEW.valor_pagar, 'FM999G999G990D00'), to_char(v_pedido, 'FM999G999G990D00');
  END IF;

  RETURN NEW;
END;
$$;

-- O cronograma sempre herda o projeto do pedido (vale tambem para chamadas de servidor, sem cabecalho).
CREATE FUNCTION public.fluxo_herda_projeto() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  SELECT projeto_id INTO NEW.projeto_id FROM pedidos_solicitados WHERE id = NEW.pedido_id;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trigger_fluxo_herda_projeto
  BEFORE INSERT ON public.pedidos_solicitados_fluxo
  FOR EACH ROW EXECUTE FUNCTION public.fluxo_herda_projeto();

