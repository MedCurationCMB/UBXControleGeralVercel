CREATE OR REPLACE FUNCTION public.atualiza_controle_orcamento() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
   INSERT INTO controle_orcamento (projeto_id, empresa, categoria, mes, ano, valor_orcamento)
   VALUES (NEW.projeto_id, NEW.empresa, NEW.categoria, NEW.mes, NEW.ano, NEW.valor_orcamento)
   ON CONFLICT (projeto_id, empresa, categoria, mes, ano)
   DO UPDATE SET valor_orcamento = EXCLUDED.valor_orcamento;
   RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.atualizar_valor_pedidos_solicitados() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE controle_orcamento co
    SET valor_pedidos_solicitados = (
        SELECT COALESCE(SUM(valor_referente), 0)
        FROM pedidos_solicitados_fluxo psf
        WHERE psf.projeto_id = co.projeto_id
          AND psf.empresa = co.empresa
          AND psf.categoria = co.categoria
          AND psf.mes = co.mes
          AND psf.ano = co.ano
          AND psf.status != 'Não Autorizado'
    )
    WHERE EXISTS (
        SELECT 1
        FROM pedidos_solicitados_fluxo psf
        WHERE psf.projeto_id = co.projeto_id
          AND psf.empresa = co.empresa
          AND psf.categoria = co.categoria
          AND psf.mes = co.mes
          AND psf.ano = co.ano
    );

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.update_valor_pedidos_solicitados() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE controle_orcamento co
  SET valor_pedidos_solicitados = (
    SELECT COALESCE(SUM(psf.valor_referente), 0)
    FROM pedidos_solicitados_fluxo psf
    WHERE psf.projeto_id = co.projeto_id
    AND psf.empresa = co.empresa
    AND psf.categoria = co.categoria
    AND CAST(psf.mes AS INTEGER) = CAST(co.mes AS INTEGER)
    AND CAST(psf.ano AS INTEGER) = CAST(co.ano AS INTEGER)
  )
  WHERE co.projeto_id = NEW.projeto_id
  AND co.empresa = NEW.empresa
  AND co.categoria = NEW.categoria
  AND CAST(co.mes AS INTEGER) = CAST(NEW.mes AS INTEGER)
  AND CAST(co.ano AS INTEGER) = CAST(NEW.ano AS INTEGER);

  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.sync_orcamento_analise() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
   registro_existente registro_orcamento_analise%ROWTYPE;
BEGIN
   SELECT * INTO registro_existente
   FROM registro_orcamento_analise
   WHERE projeto_id = NEW.projeto_id
   AND empresa = NEW.empresa
   AND categoria = NEW.categoria
   AND mes = NEW.mes
   AND ano = NEW.ano;

   IF FOUND THEN
       UPDATE registro_orcamento_analise
       SET valor_orcamento_vigente = NEW.valor_orcamento
       WHERE projeto_id = NEW.projeto_id
       AND empresa = NEW.empresa
       AND categoria = NEW.categoria
       AND mes = NEW.mes
       AND ano = NEW.ano;
   ELSE
       INSERT INTO registro_orcamento_analise (
           projeto_id, empresa, categoria, mes, ano, valor_orcamento_vigente, valor_orcamento_inicial
       )
       VALUES (
           NEW.projeto_id, NEW.empresa, NEW.categoria, NEW.mes, NEW.ano, NEW.valor_orcamento, NEW.valor_orcamento
       );
   END IF;

   RETURN NEW;
END;
$$;

